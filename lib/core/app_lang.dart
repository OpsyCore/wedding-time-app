/// مدیریت زبان سراسری — فارسی / English
class AppLang extends ChangeNotifier {
  AppLang._();
  static final AppLang I = AppLang._();

  static const String prefKey = 'language';
  static const supported = ['fa', 'en'];

  String _code = 'fa';
  bool _ready = false;

  String get code => _code;
  bool get isFa => _code == 'fa';
  bool get isEn => _code == 'en';
  bool get ready => _ready;
  bool get isRtl => _code == 'fa';

  TextDirection get direction =>
      isRtl ? TextDirection.rtl : TextDirection.ltr;

  Locale get locale => Locale(_code);

  Future<void> load() async {
    final prefs = await SharedPreferences.getInstance();
    final saved = (prefs.getString(prefKey) ?? 'fa').toLowerCase();
    _code = supported.contains(saved) ? saved : 'fa';
    _ready = true;
    notifyListeners();
  }

  Future<void> setLanguage(String code) async {
    final next = code.toLowerCase();
    if (!supported.contains(next)) return;
    if (_code == next) return;

    _code = next;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(prefKey, next);

    final uid = FirebaseAuth.instance.currentUser?.uid;
    if (uid != null) {
      try {
        await FirebaseFirestore.instance.collection('users').doc(uid).set({
          'language': next,
          'updatedAt': FieldValue.serverTimestamp(),
        }, SetOptions(merge: true));
      } catch (_) {}
    }

    notifyListeners();
  }

  String t(String key) {
    final map = _tables[_code] ?? _tables['fa']!;
    if (map.containsKey(key)) return map[key]!;
    return _tables['fa']![key] ?? key;
  }

  static String tr(String key) => I.t(key);

    /// ترجمه برای یک کد زبان (مثلاً پیش‌نمایش onboarding قبل از setLanguage)
  String tIn(String langCode, String key) {
    final code =
        supported.contains(langCode.toLowerCase()) ? langCode.toLowerCase() : 'fa';
    final map = _tables[code] ?? _tables['fa']!;
    if (map.containsKey(key)) return map[key]!;
    return _tables['fa']![key] ?? key;
  }

  static String trIn(String langCode, String key) => I.tIn(langCode, key);
}

class AppDir extends StatelessWidget {
  const AppDir({super.key, required this.child});
  final Widget child;

  @override
  Widget build(BuildContext context) {
    return Directionality(
      textDirection: AppLang.I.direction,
      child: child,
    );
  }
}

